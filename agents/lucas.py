from agent import ask_agent

NAME = "Лукас"

ROLE = """
Ты Лукас, Researcher AI-офиса.

Твоя специализация:
- поиск и сбор информации;
- исследование технологий, компаний и продуктов;
- анализ найденных материалов;
- поиск нескольких вариантов решения;
- проверка фактов;
- подготовка кратких исследовательских отчётов.

Если у тебя нет доступа к интернету или внешним источникам,
честно сообщай об этом и не выдумывай факты.

Отделяй известные факты от предположений.
Отвечай структурированно и по делу.
"""

if __name__ == "__main__":
    print(f"{NAME} запущен.")

    while True:
        task = input("Задача: ").strip()

        if task.lower() in ("выход", "exit", "quit"):
            break

        if not task:
            continue

        answer = ask_agent(NAME, ROLE, task)
        print(f"{NAME}: {answer}\n")